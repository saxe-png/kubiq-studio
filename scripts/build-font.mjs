// Turns assets/fonts/Rocpar.otf into the two things the site ships:
//   src/assets/fonts/rocpar.woff2   webfont for headings set as text
//   src/generated/rocpar.ts         outlines of the title letters + the code points the font covers
// Run with `npm run font`. Both outputs are committed, so a normal build needs neither the OTF
// (which stays out of git) nor this script.
import fs from 'node:fs';
import path from 'node:path';
import opentype from 'opentype.js';
import wawoff2 from 'wawoff2';

const root = path.resolve(import.meta.dirname, '..');
const source = path.join(root, 'assets/fonts/Rocpar.otf');
const bytes = fs.readFileSync(source);
const font = opentype.parse(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));

// The title is drawn from outlines so it can be thickened, outlined and animated.
// Rocpar is unicase: lowercase letters are cap-height alternates, so both sets are exported.
const TITLE_WORDS = ['kubiq', 'studios'];
const titleChars = [...new Set(TITLE_WORDS.flatMap((w) => [...w, ...w.toUpperCase()]))];

// The gap that separates Q's bottom bar from its tail is only 55 units and closes as soon as the
// title is emboldened, turning KUBIQ into KUBIO. Pulling the end of the bar back keeps it open.
const Q_BAR_END_X = 342.7;
const Q_BAR_SHORTEN = 80;

const round = (v) => {
  const r = Math.round(v * 100) / 100;
  return Math.abs(r) < 0.005 ? 0 : r;
};

// opentype.js 2.0 drops the close command and can glue numbers together in toPathData(), so the
// path is serialised here: one closed subpath per contour, y flipped to SVG's downward axis.
function outline(char) {
  const glyph = font.charToGlyph(char);
  const isQ = char === 'q' || char === 'Q';
  const fix = (x, y) => (isQ && y < 110 && Math.abs(x - Q_BAR_END_X) < 6 ? x - Q_BAR_SHORTEN : x);

  const contours = [];
  let current = null;
  for (const c of glyph.path.commands) {
    if (c.type === 'M') {
      current = { start: [fix(c.x, c.y), c.y], segments: [] };
      contours.push(current);
    } else if (c.type === 'L') {
      current.segments.push({ type: 'L', x: fix(c.x, c.y), y: c.y });
    } else if (c.type === 'C') {
      current.segments.push({ type: 'C', x1: c.x1, y1: c.y1, x2: c.x2, y2: c.y2, x: c.x, y: c.y });
    } else if (c.type === 'Q') {
      current.segments.push({ type: 'Q', x1: c.x1, y1: c.y1, x: c.x, y: c.y });
    }
  }

  let d = '';
  for (const contour of contours) {
    let [px, py] = contour.start;
    d += `M${round(px)} ${round(-py)}`;
    const segments = contour.segments.filter((s, i, all) => {
      // drop the explicit return to the start point; Z closes the contour with a proper join
      const last = i === all.length - 1;
      return !(last && s.type === 'L' && round(s.x) === round(contour.start[0]) && round(s.y) === round(contour.start[1]));
    });
    for (const s of segments) {
      if (s.type === 'L') {
        if (round(s.x) === round(px) && round(s.y) === round(py)) continue;
        d += `L${round(s.x)} ${round(-s.y)}`;
      } else if (s.type === 'C') {
        d += `C${round(s.x1)} ${round(-s.y1)} ${round(s.x2)} ${round(-s.y2)} ${round(s.x)} ${round(-s.y)}`;
      } else {
        d += `Q${round(s.x1)} ${round(-s.y1)} ${round(s.x)} ${round(-s.y)}`;
      }
      px = s.x;
      py = s.y;
    }
    d += 'Z';
  }

  const box = glyph.getBoundingBox();
  return { d, adv: glyph.advanceWidth, ink: round(box.x2), descent: round(Math.max(0, -box.y1)) };
}

const glyphs = Object.fromEntries(titleChars.map((ch) => [ch, outline(ch)]));
const codePoints = Object.keys(font.tables.cmap.glyphIndexMap)
  .map(Number)
  .filter((cp) => cp >= 32 && cp !== 160)
  .sort((a, b) => a - b);

const stem = Math.round(font.charToGlyph('i').getBoundingBox().x2 - font.charToGlyph('i').getBoundingBox().x1);
const bearing = Math.round(font.charToGlyph('i').advanceWidth - font.charToGlyph('i').getBoundingBox().x2);

const module = `// Generated by scripts/build-font.mjs from Rocpar.otf. Do not edit by hand.

/** Font units per em. */
export const UPM = ${font.unitsPerEm};
/** Height of every letter (the font is unicase). */
export const CAP = ${font.tables.os2.sCapHeight};
/** Stroke thickness of the letters. */
export const STEM = ${stem};
/** Empty space after each letter; letters have no space before them. */
export const BEARING = ${bearing};
/** Advance of the space character. */
export const SPACE = ${font.charToGlyph(' ').advanceWidth};

/** Every character Rocpar can draw. Anything else falls back to another font. */
export const CODE_POINTS: readonly number[] = ${JSON.stringify(codePoints)};

export interface GlyphOutline {
  /** Closed SVG path in font units, baseline at y = 0, letters extending upward into negative y. */
  d: string;
  /** Advance width. */
  adv: number;
  /** Right edge of the drawn shape. */
  ink: number;
  /** How far the shape reaches below the baseline. */
  descent: number;
}

/** Outlines of the letters used by the title, in both letterform sets. */
export const GLYPHS: Readonly<Record<string, GlyphOutline>> = ${JSON.stringify(glyphs, null, 2)};
`;

fs.mkdirSync(path.join(root, 'src/generated'), { recursive: true });
fs.writeFileSync(path.join(root, 'src/generated/rocpar.ts'), module);

const woff2 = Buffer.from(await wawoff2.compress(bytes));
const back = Buffer.from(await wawoff2.decompress(woff2));
if (back.length !== bytes.length) {
  console.warn(`round trip changed size: ${bytes.length} -> ${back.length} bytes (tables are re-packed; checking the font still parses)`);
}
const reparsed = opentype.parse(back.buffer.slice(back.byteOffset, back.byteOffset + back.byteLength));
if (reparsed.numGlyphs !== font.numGlyphs) throw new Error('WOFF2 round trip lost glyphs');

fs.mkdirSync(path.join(root, 'src/assets/fonts'), { recursive: true });
fs.writeFileSync(path.join(root, 'src/assets/fonts/rocpar.woff2'), woff2);

console.log(`rocpar.woff2  ${woff2.length} bytes (from ${bytes.length})`);
console.log(`rocpar.ts     ${titleChars.length} glyphs, ${codePoints.length} code points, stem ${stem}, bearing ${bearing}`);
for (const ch of ['q', 'Q', 'u']) console.log(`  ${ch}: ${glyphs[ch].d.slice(0, 150)}…`);
